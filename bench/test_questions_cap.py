def main() -> int:
    bad = 0
    polish.questions_mode = "heard"
    for name, raw, polished, want in CASES:
        got = polish.no_false_question(raw, polished)
        ok = got == want
        bad += not ok
        print(("[v] " if ok else "[X] ") + name)
        if not ok:
            print("    надо:", want)
            print("    вышло:", got)

    polish.questions_mode = "corrector"
    for name, raw, polished, want in OLD_MODE:
        got = polish.no_false_question(raw, polished)
        ok = got == want
        bad += not ok
        print(("[v] " if ok else "[X] ") + name)
        if not ok:
            print("    надо:", want)
            print("    вышло:", got)
    polish.questions_mode = "heard"

    total = len(CASES) + len(OLD_MODE)
    print(f"\n{total - bad} of {total} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
