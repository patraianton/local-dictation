# -*- coding: utf-8 -*-
"""Знаки препинания вокруг откаченного слова.

Замок constrain() берёт у корректора только знаки, заглавные буквы и термины,
а слова возвращает как сказано. Но знак, стоявший рядом с выброшенным словом,
описывает фразу, которой больше нет, — и раньше он оставался в тексте.

Все случаи — настоящие, из журнала за 21-22.08.2026. Ни микрофона, ни LM Studio.

    ..\\.venv\\Scripts\\python.exe test_rollback_sep.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from stt.polish import constrain  # noqa: E402

ALLOWED = {"intercom", "claude", "handover"}

# (зачем, что услышали, что вернул корректор, что должно получиться)
CASES = [
    (
        "корректор заменил «все время» на «всегда» — вернули слова, "
        "запятая от «всегда» уйти забыла (22.08, 11:20)",
        "Мы тут пока не едем и я все время жду.",
        "Мы тут пока не едем и всегда жду.",
        "Мы тут пока не едем и я все время жду.",
    ),
    (
        "корректор выбросил «как» и разорвал фразу надвое — вернули «как», "
        "а точка с заглавной буквой осталась (22.08, 11:07)",
        "что-то, как откуда взялась эта коробка на складе?",
        "что-то. Откуда взялась эта коробка на складе?",
        "что-то, как откуда взялась эта коробка на складе?",
    ),
    (
        "выдуманное слово «упакованный» откачено вместе со своим оформлением "
        "(22.08, 11:20)",
        "Обычно ты когда пакуешь заказ, я вижу заказ такой-то упакованок.",
        "Обычно ты, когда пакуешь заказ, я вижу заказ такой-то упакованный.",
        "Обычно ты, когда пакуешь заказ, я вижу заказ такой-то упакованок.",
    ),
    (
        "дописанное слово «когда» не приняли — его запятая тоже не нужна",
        "я новую смену начал",
        "я, когда новую смену начал",
        "я новую смену начал",
    ),
    # --- ничего не откатывали: знаки корректора остаются как были ---
    (
        "обычная запятая на своём месте — не трогаем",
        "Я думаю что это нормально",
        "Я думаю, что это нормально.",
        "Я думаю, что это нормально.",
    ),
    (
        "тире корректора остаётся: на замерах 14-15.08 оно почти всегда к месту",
        "Интерком это chat widget",
        "Intercom — это chat widget.",
        "Intercom — это chat widget.",
    ),
    (
        "точка в конце и заглавная в начале — обычная работа корректора",
        "он три дня лежал",
        "Он три дня лежал.",
        "Он три дня лежал.",
    ),
]


def main() -> int:
    bad = 0
    for why, raw, polished, want in CASES:
        got = constrain(raw, polished, ALLOWED, set())
        ok = got == want
        bad += not ok
        print(("[v] " if ok else "[X] ") + why)
        if not ok:
            print("    услышали:", raw)
            print("    корректор:", polished)
            print("    надо:    ", want)
            print("    вышло:   ", got)
    print(f"\n{len(CASES) - bad} of {len(CASES)} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
