# -*- coding: utf-8 -*-
"""Словарь не запоминает чужие знаки препинания.

22.08.2026 в fixes.tsv нашлась выученная пара «все -> — всё». Корректор
однажды поставил тире перед «всё» из-за соседних слов, а самообучение приняло
тире за часть слова. После этого КАЖДОЕ «все» в речи превращалось в «— всё»:

    «Там все по задачам»          -> «Там — всё по задачам»
    «и я все время подозреваю»    -> «и я — всё время подозреваю»
    «Ещё раз использую — все ...» -> «Ещё раз использую — — всё ...»

    ..\\.venv\\Scripts\\python.exe test_learn_punct.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from stt.learn import candidate_pairs  # noqa: E402

# (зачем, что услышали, что вернул корректор, какие пары можно запоминать)
CASES = [
    (
        "тире от корректора не попадает в словарь (настоящий случай 22.08)",
        "Там все по задачам.",
        "Там — всё по задачам.",
        [],
    ),
    (
        "запятая — тоже оформление, а не часть слова",
        "Ну вот все закончилось.",
        "Ну, всё закончилось.",
        [],
    ),
    (
        "двоеточие в начале замены не запоминаем",
        "Дальше вот эта надпись что это за апдейт.",
        "Дальше вот эта надпись: что это за апдейт.",
        [],
    ),
    # --- обычные замены как работали, так и работают ---
    (
        "имя, расслышанное неверно, запоминается",
        "Поставь это на Архана.",
        "Поставь это на Орхана.",
        [("Архана", "Орхана")],
    ),
    (
        "дефис ВНУТРИ названия — часть написания, не оформление",
        "Положи в тимопс.",
        "Положи в team-ops.",
        [("тимопс", "team-ops")],
    ),
    (
        "и он больше не разъезжается пробелами (было «follow - up»)",
        "Это фоллоу ап письмо.",
        "Это follow-up письмо.",
        [("фоллоу ап", "follow-up")],
    ),
    (
        "«е»/«ё» по-прежнему не запоминаем: это разные слова",
        "Все закончилось.",
        "Всё закончилось.",
        [],
    ),
]


def main() -> int:
    bad = 0
    for why, raw, polished, want in CASES:
        got = candidate_pairs(raw, polished)
        ok = got == want
        bad += not ok
        print(("[v] " if ok else "[X] ") + why)
        if not ok:
            print("    услышали: ", raw)
            print("    корректор:", polished)
            print("    надо:     ", want)
            print("    вышло:    ", got)
    print(f"\n{len(CASES) - bad} of {len(CASES)} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
