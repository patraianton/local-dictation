# -*- coding: utf-8 -*-
"""Две починки от 29.08.2026: выдуманные субтитры и потерянная заглавная.

1. Распознавалка, не услышав речи, иногда всё равно выдаёт текст — заученные
   титры из тех субтитров, на которых её учили: «Субтитры создавал DimaTorzok»,
   «Продолжение следует...», «Редактор субтитров А. Семкин». Она выдаёт их с
   таким же уверенным видом, как настоящую расшифровку. За 18 дней таких
   случаев девять, последний — 29.08 в 09:10. Худший: 25.08 в 23:39 запись
   длиной 238 секунд (почти четыре минуты речи) вышла тремя словами
   «Продолжение следует...».

2. Правщику разрешено ставить заглавную букву, и на этот случай в polish.py
   есть откат. Обратного правила не было — он мог заглавную ОТНЯТЬ, и надиктовка
   начиналась с маленькой буквы: «Что вообще делать?» вставилось как «что
   вообще делать?» (29.08, и ещё дважды за четыре дня до того).

    ..\\.venv\\Scripts\\python.exe test_ghost_and_case.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from stt.asr import just_a_sound, subtitle_ghost  # noqa: E402
from stt.polish import allowed_words, constrain  # noqa: E402

TERMS = ["Claude Code", "herdr", "SafetyWing", "Codex"]
ALLOWED = allowed_words(TERMS)


def fail(msg):
    print(f"[X] {msg}")
    sys.exit(1)


def main():
    ok = []

    # --- 1. Настоящие случаи из логов опознаются ---
    # Слева — ровно то, что лежит в logs/*.jsonl, вместе с точками и датами.
    from_logs = [
        "Субтитры делал DimaTorzok",              # 14.08 09:55, 0.55 с
        "Продолжение следует...",                 # 21.08 18:01, 1.72 с
        "Субтитры создавал DimaTorzok",           # 23.08 20:12, 5.12 с
        "Редактор субтитров А. Семкин",           # 25.08 11:27, 1.28 с
        "Субтитры создавал DimaTorzok.",          # 28.08 22:53, 0.77 с
        # Самая частая живая форма: редактор и корректор с инициалами. 10.09 в 23:02
        # (3,75 с) она прошла как речь — в ней 29 букв после фразы, а предел 24.
        "Редактор субтитров А.Семкин Корректор А.Егорова",
        "Редактор субтитров А. Семкин, корректор А. Егорова",
        "Корректор субтитров А.Егорова.",
    ]
    for text in from_logs:
        if not subtitle_ghost(text):
            fail(f"выдуманная фраза не опознана: {text!r}")
    ok.append(f"все {len(from_logs)} видов заглушек из логов опознаются")

    # --- 2. Настоящая речь про субтитры не трогается ---
    # Тут и проходит граница: диктовка про субтитры — обычная рабочая фраза.
    real = [
        "сделай субтитры к этому ролику и залей на канал",
        "Продолжение следует, я потом допишу этот кусок про агентов",
        "спроси у редактора субтитров, когда будет готово",
        "подписывайтесь на канал — нет, это я диктую текст для лендинга",
        "Что вообще делает эта лампочка?",
        "Редактор субтитров должен проверить файл по списку",
        "Корректор А.Егорова проверила таблицу",
        "",
    ]
    for text in real:
        got = subtitle_ghost(text)
        if got:
            fail(f"настоящая речь принята за заглушку: {text!r} -> {got!r}")
    ok.append("настоящая речь про субтитры и продолжение не задета")

    # --- 2б. Кашель, мычание и смех целой записью не вставляются (06.10.2026) ---
    sounds = ["Кхм.", "Ммм.", "Ммм...", "Ахаха.", "Хм.", "Кхе-кхе.", "Гм.", "Пфф.",
              "Ха-ха-ха.", "Эээм...", "Хмм, ммм.", "Ааа...", "А-а-а.", "Аааа…",
              "А-а-а-а-а-а...", "М-м-м-м-м."]
    for text in sounds:
        if not just_a_sound(text):
            fail(f"звук не опознан: {text!r}")
    words = ["Ммм, давай.", "Ага.", "Угу.", "А.", "Ха.", "Хм, интересно.", "Мм, нет.",
             "Эм, слушай.", "Мама.", "Хамам.", "Кхм, так вот, открой файл.", "",
             "Ааа, понял.", "ООО.", "А-а, ясно.", "И-и-и-и, вот."]
    for text in words:
        if just_a_sound(text):
            fail(f"слово принято за звук: {text!r}")
    ok.append("запись из одного кашля или «Ммм» не вставляется, ответы «ага», «угу», «А» остаются")

    # --- 3. Заглавная буква в начале надиктовки не теряется ---
    # Ровно тот случай с будильником: правщик вернул всё то же самое, только
    # первое слово с маленькой буквы.
    cases = [
        ("Куда вообще ехать? Это будет долго.",
         "куда вообще ехать? Это будет долго.",
         "Куда вообще ехать? Это будет долго."),
        ("Отчитайся по спринту.", "отчитайся по спринту.",
         "Отчитайся по спринту."),
        ("Сделай это сегодня.", "Сделай это сегодня.",
         "Сделай это сегодня."),
    ]
    for raw, polished, want in cases:
        got = constrain(raw, polished, ALLOWED)
        if got != want:
            fail(f"заглавная не восстановлена:\n  сказано : {raw}\n"
                 f"  правщик : {polished}\n  вышло   : {got}\n  надо    : {want}")
    ok.append("заглавная буква в начале надиктовки восстанавливается")

    # --- 4. ...а законная правка регистра В СЕРЕДИНЕ по-прежнему проходит ---
    # Распознавалка иногда ставит заглавную посреди фразы, и убрать её —
    # правильная работа правщика. Чинить надо только первое слово.
    got = constrain("сделай это Сегодня", "Сделай это сегодня", ALLOWED)
    if "Сегодня" in got:
        fail(f"правщику запретили убирать лишнюю заглавную в середине: {got!r}")
    if not got.startswith("С"):
        fail(f"заглавная в начале не поставлена: {got!r}")
    ok.append("лишняя заглавная в середине фразы по-прежнему убирается")

    # --- 5. Если человек сам начал со строчной, ничего не выдумываем ---
    got = constrain("ну и хрен с ним", "ну и хрен с ним", ALLOWED)
    if got != "ну и хрен с ним":
        fail(f"заглавная приписана там, где её не было: {got!r}")
    ok.append("своя строчная буква в начале не переписывается")

    # --- 6. Слово, взятое в пару словаря «для контекста», не становится термином ---
    # Пара «кончено это → конечно это» сделала обычное «это» термином, и
    # заглавная правщика на нём осталась посреди фразы (07.10.2026).
    class FakeFixes:
        pairs = {"кончено это": ("конечно это", 0, "manual"),
                 "рой opus": ("рой Opus", 0, "manual"),
                 "все-таки": ("всё-таки", 0, "manual")}
    allowed = allowed_words(TERMS, FakeFixes())
    for w in ("это", "рой", "таки"):
        if w in allowed:
            fail(f"слово из пары словаря стало термином: {w!r}")
    for w in ("конечно", "opus", "всё", "herdr"):
        if w not in allowed:
            fail(f"нужное слово выпало из терминов: {w!r}")
    got = constrain("Мы всё проверили, как это вообще работает.",
                    "Мы всё проверили? Это вообще работает?", allowed)
    if "Это" in got:
        fail(f"заглавная посреди фразы осталась: {got!r}")
    # То же, когда обычное слово стоит в глоссарии как имя: «Это» среди людей.
    named = allowed_words(TERMS + ["Это"], FakeFixes())
    got = constrain("Мы всё проверили, как это вообще работает.",
                    "Мы всё проверили? Это вообще работает?", named, {"это", "мы"})
    if "Это" in got:
        fail(f"заглавная обычного слова-имени посреди фразы осталась: {got!r}")
    got = constrain("открой codex и посмотри", "Открой Codex и посмотри", named, {"это", "мы"})
    if "Codex" not in got:
        fail(f"термин потерял заглавную: {got!r}")
    # Термин, который всегда пишется со строчной («herdr»), посреди фразы
    # заглавную от правщика не получает; в начале предложения — получает.
    got = constrain("скажи, что herdr уже готов", "Скажи, что Herdr уже готов", named)
    if "Herdr" in got:
        fail(f"строчный термин получил заглавную посреди фразы: {got!r}")
    got = constrain("herdr уже готов", "Herdr уже готов", named)
    if not got.startswith("Herdr"):
        fail(f"строчный термин в начале предложения потерял заглавную: {got!r}")
    if "herdr" not in named.lower_only or "codex" in named.lower_only:
        fail(f"неверный список строчных терминов: {sorted(named.lower_only)}")
    ok.append("слово, взятое в пару словаря для связки, не получает права на заглавную")

    # --- 7. Буква «ё», которую написала распознавалка, не пропадает ---
    got = constrain("Ну ёлки, зачем ты мне это шлёшь", "Ну елки, зачем ты мне это шлешь?", ALLOWED)
    if "ёлки" not in got or "шлёшь" not in got:
        fail(f"правщик убрал «ё»: {got!r}")
    got = constrain("Ёлки, опять сломалось", "Елки, опять сломалось.", ALLOWED)
    if not got.startswith("Ёлки"):
        fail(f"заглавная «Ё» потерялась: {got!r}")
    got = constrain("всё пришли сюда", "Все пришли сюда.", ALLOWED)
    if not got.startswith("Все"):
        fail(f"«всё/все» правщику выбирать можно: {got!r}")
    ok.append("«ё», которую услышала распознавалка, правщик не убирает (кроме «всё/все»)")

    # --- 8. Приказ, который правщик переделал в обещание, теряет только его ---
    # Правщик ответил на приказ («открывай» -> «открываю»), замок вернул
    # сказанное слово — и вместе с ним выбросил все запятые вокруг (08.10.2026).
    got = constrain("ладно открывай и проверяй конечно пиши что нашёл",
                    "Ладно, открываю и проверяю, конечно, пишу что нашёл.", ALLOWED)
    if got != "Ладно, открывай и проверяй, конечно, пиши что нашёл.":
        fail(f"запятые вокруг возвращённого приказа пропали: {got!r}")
    got = constrain("Проверь мы уже в нужной ветке.",
                    "Проверяем, мы уже в нужной ветке?", ALLOWED)
    if not got.startswith("Проверь, мы"):
        fail(f"запятая после приказа пропала: {got!r}")
    # Другая перемена окончания меняет роль слова, и запятые правщика там чужие.
    got = constrain("отправь панель собрать отчёт", "Отправь панель, собери отчёт.", ALLOWED)
    if "панель," in got or "собрать" not in got:
        fail(f"запятая от чужого прочтения осталась: {got!r}")
    got = constrain("Вначале укажи, история.", "Вначале укажи историю.", ALLOWED)
    if got != "Вначале укажи, история.":
        fail(f"своя запятая распознавалки пропала: {got!r}")
    ok.append("приказ, переделанный в обещание, возвращается вместе со своими запятыми")

    # --- 9. «Да нет» без запятой остаётся мягким «нет» (09.10.2026) ---
    got = constrain("Да нет, всё нормально, я сам открою.", "Да, нет, всё нормально, я сам открою.", ALLOWED)
    if not got.startswith("Да нет, всё"):
        fail(f"правщик разбил «да нет» запятой: {got!r}")
    got = constrain("не спеши да нет не надо", "Не спеши, да, нет, не надо.", ALLOWED)
    if "да нет" not in got:
        fail(f"«да нет» посреди фразы разбито запятой: {got!r}")
    # Сказанное с запятой остаётся как было.
    got = constrain("Да, нет, наверное, завтра.", "Да, нет, наверное, завтра.", ALLOWED)
    if not got.startswith("Да, нет,"):
        fail(f"сказанная запятая пропала: {got!r}")
    # «Да не надо» — то же самое: отмахнуться, а не согласиться.
    got = constrain("Да не надо мне эту коробку.", "Да, не надо мне эту коробку.", ALLOWED)
    if not got.startswith("Да не надо"):
        fail(f"правщик разбил «да не» запятой: {got!r}")
    got = constrain("Ну да не знаю я, где склад.", "Ну, да, не знаю я, где склад.", ALLOWED)
    if "да не знаю" not in got:
        fail(f"«да не» посреди фразы разбито запятой: {got!r}")
    got = constrain("Да, не надо, сам отнесу.", "Да, не надо, сам отнесу.", ALLOWED)
    if not got.startswith("Да, не надо"):
        fail(f"сказанная запятая в «да, не» пропала: {got!r}")
    got = constrain("Да нет, не надо. Да, не знаю.", "Да, нет, не надо. Да, не знаю.", ALLOWED)
    if not got.startswith("Да нет, не надо. Да, не знаю"):
        fail(f"«да нет» и «да, не» в одной записи считаются порознь: {got!r}")
    # «Да никогда», «да ничего страшного» (16.10.2026) — тоже не согласие.
    got = constrain("Да никогда он сам не позвонит.", "Да, никогда он сам не позвонит.", ALLOWED)
    if not got.startswith("Да никогда"):
        fail(f"правщик разбил «да никогда» запятой: {got!r}")
    got = constrain("Ну да ничего страшного, завтра.", "Ну, да, ничего страшного, завтра.", ALLOWED)
    if "да ничего" not in got:
        fail(f"«да ничего» посреди фразы разбито запятой: {got!r}")
    got = constrain("Да, никто не пришёл.", "Да, никто не пришёл.", ALLOWED)
    if not got.startswith("Да, никто"):
        fail(f"сказанная запятая в «да, никто» пропала: {got!r}")
    got = constrain("Да нижний ящик открой.", "Да, нижний ящик открой.", ALLOWED)
    if not got.startswith("Да, нижний"):
        fail(f"«ни» в начале обычного слова принято за отрицание: {got!r}")
    ok.append("в «да нет», «да не» и «да никогда» правщик не ставит запятую")

    # --- Прямая речь в кавычках после двоеточия — с заглавной (14.10.2026:
    #     правщик оставлял маленькую букву в 9 из 38 таких кавычек) ---
    got = constrain("мы придём и скажем вот вам готовый набор",
                    "Мы придём и скажем: «вот вам готовый набор».", ALLOWED)
    if "«Вот вам" not in got:
        fail(f"прямая речь после двоеточия начата с маленькой: {got!r}")
    got = constrain("он пишет open the door и уходит",
                    "Он пишет: «open the door» и уходит.", ALLOWED)
    if "«open the door»" not in got:
        fail(f"латинское слово в кавычках получило заглавную: {got!r}")
    got = constrain("слово «склад» тут лишнее", "Слово «склад» тут лишнее.", ALLOWED)
    if "«склад»" not in got:
        fail(f"кавычки без двоеточия получили заглавную: {got!r}")
    ok.append("прямая речь в кавычках после двоеточия — с заглавной, остальное не тронуто")

    for line in ok:
        print(f"[v] {line}")
    print("\nвсё сошлось")


if __name__ == "__main__":
    main()
