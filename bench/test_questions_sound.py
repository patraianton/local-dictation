# -*- coding: utf-8 -*-
"""Вопрос, который слышно голосом, и вопрос после слова-паразита.

Два правила, добавленные 10.09.2026, оба по разбору настоящих надиктовок за
08-10.09 (421 штука, из них 148 вопросов; знак доходил до человека в 124).

1. Слово-паразит перед вопросительным словом больше не считается отдельной
   мыслью. «Хорошо, как скоро мы это закончим?» — Антон спросил это три раза
   подряд, каждый раз получил точку и каждый раз переспрашивал.

2. Если ни распознавалка, ни правщик вопроса не нашли, распознавалку
   спрашивают ещё раз: какой конец лучше ложится на запись, «.» или «?».

Ни микрофона, ни LM Studio, ни видеокарты здесь не надо.

    ..\\.venv\\Scripts\\python.exe test_questions_sound.py
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from stt import asr as A  # noqa: E402
from stt import polish  # noqa: E402

# (что услышала распознавалка, что вернул правщик, что должно остаться)
FILLER_CASES = [
    (
        "«Хорошо,» перед вопросительным словом — вопрос остаётся "
        "(10.09.2026, спрошено трижды подряд)",
        "Хорошо, как скоро мы это закончим.",
        "Как скоро мы это закончим?",
        "Хорошо, как скоро мы это закончим?",
    ),
    (
        "то же самое, другой раз",
        "Хорошо, как скоро закончится.",
        "Как скоро закончится?",
        "Хорошо, как скоро закончится?",
    ),
    (
        "«Ну и,» — тоже слова-паразиты",
        "Ну и что теперь с этим делать.",
        "Ну и что теперь с этим делать?",
        "Ну и что теперь с этим делать?",
    ),
    (
        "настоящая мысль перед «что» — знак по-прежнему снимается "
        "(придаточное, не вопрос)",
        "вот тут написано, что у тебя memory missing.",
        "Вот тут написано, что у тебя memory missing?",
        "Вот тут написано, что у тебя memory missing.",
    ),
    (
        "приказ с «что» внутри — знак снимается",
        "разбирайся, что с ним не так.",
        "Разбирайся, что с ним не так?",
        "Разбирайся, что с ним не так.",
    ),
    (
        "четыре слова перед вопросительным — это уже мысль, а не паразиты",
        "Я вчера тебе говорил, что мы это уже сделали.",
        "Я вчера тебе говорил, что мы это уже сделали?",
        "Я вчера тебе говорил, что мы это уже сделали.",
    ),
]


class FakeAsr:
    """Распознавалка, которая «слышит» заранее назначенную разницу."""

    def __init__(self, d):
        self.d = d
        self.asked = []

    def question_score(self, audio, text):
        self.asked.append(text)
        return self.d


class FakeDictation:
    """Ровно те поля, которые нужны ask_the_sound."""

    def __init__(self, d, enabled=True, threshold=-1.0):
        self.asr = FakeAsr(d)
        self.sound_questions = enabled
        self.sound_threshold = threshold
        self.last_sound_q = "мусор с прошлой надиктовки"


def fail(msg):
    print(f"[X] {msg}")
    sys.exit(1)


def main():
    ok = []
    allowed = set()

    # --- 1. Слова-паразиты ---
    polish.questions_mode = "heard"
    for name, raw, model, want in FILLER_CASES:
        got = polish.constrain(raw, model, allowed, set())
        if got != want:
            fail(f"{name}\n     надо: {want}\n     вышло: {got}")
    ok.append(f"слова-паразиты: {len(FILLER_CASES)} случаев из журнала сошлись")

    # --- 2. Знак по звуку: ставится только выше порога ---
    from stt.__main__ import Dictation

    ask = Dictation.ask_the_sound
    data = np.zeros(16000, dtype=np.float32)
    d = FakeDictation(d=+0.5)
    got = ask(d, data, "Мы ссылки сделали на эти статьи.", "Мы ссылки сделали на эти статьи.")
    if got != "Мы ссылки сделали на эти статьи?":
        fail(f"знак по звуку не поставлен: {got!r}")
    if d.asr.asked != ["Мы ссылки сделали на эти статьи."]:
        fail(f"взвешивали не то, что услышала распознавалка: {d.asr.asked}")
    ok.append("звук говорит «вопрос» — знак поставлен")

    d = FakeDictation(d=-1.0)      # ровно порог: строго больше, значит нет
    if ask(d, data, "Получается все сделали.", "Получается, все сделали.") is not None:
        fail("на самом пороге знак поставлен, а не должен")
    d = FakeDictation(d=-9.0)
    if ask(d, data, "Возьми задачу и сделай.", "Возьми задачу и сделай.") is not None:
        fail("звук говорит «не вопрос», а знак поставлен")
    ok.append("ниже порога знак не ставится")

    # --- 3. Не трогаем то, где вопрос уже есть ---
    d = FakeDictation(d=+5.0)
    if ask(d, data, "Почему упало?", "Почему упало?") is not None:
        fail("влезли в надиктовку, где вопрос уже стоял")
    if d.asr.asked:
        fail("зря потратили время на взвешивание")
    if d.last_sound_q is not None:
        fail("оценка от прошлой надиктовки не сброшена")
    ok.append("где вопрос уже есть — ничего не считаем")

    # --- 4. Выключается настройкой, и сбой не ломает надиктовку ---
    d = FakeDictation(d=+5.0, enabled=False)
    if ask(d, data, "Мы это сделали.", "Мы это сделали.") is not None:
        fail("выключенное правило всё равно сработало")
    d = FakeDictation(d=None)
    if ask(d, data, "Мы это сделали.", "Мы это сделали.") is not None:
        fail("когда взвесить не удалось, текст всё равно изменили")
    ok.append("выключается настройкой; когда взвесить нельзя — текст как был")

    # --- 5. Длинная запись не взвешивается: модель читает окно в 30 секунд ---
    long_audio = np.zeros(16000 * 40, dtype=np.float32)
    real = A.Asr({"asr": {}}, [])
    real.model = object()          # не None, но и не рабочая — до неё не дойдёт
    if real.question_score(long_audio, "Что-то очень длинное.") is not None:
        fail("сорокасекундную запись взвесили, хотя конец в окно не влезает")
    if real.question_score(np.zeros(16000, dtype=np.float32), "   ") is not None:
        fail("пустой текст взвесили")
    ok.append("длинная запись и пустой текст не взвешиваются")

    # --- 6. Замена последнего знака ---
    for src, want in (("Точка.", "Точка?"), ("Многоточие...", "Многоточие?"),
                      ("Без знака", "Без знака?"), ("Восклицание!", "Восклицание?")):
        if A._with_mark(src, "?") != want:
            fail(f"замена знака: {src!r} -> {A._with_mark(src, '?')!r}, надо {want!r}")
    ok.append("последний знак заменяется, а не приписывается вторым")

    print("[v] " + "\n[v] ".join(ok))
    print("\nвсё сошлось")


if __name__ == "__main__":
    main()
